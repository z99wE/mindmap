// 2. MEMORY EVOLUTION SYSTEM
// ====================
class MemoryManager {
  constructor(userId) {
    this.userId = userId;
    this.memories = new Map(); // User-isolated memory storage
    console.log(`🧠 Memory manager created for user: ${userId}`);
  }

  addMemory(text, metadata = {}, tags = []) {
    const memoryId = `mem_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`;
    const memory = {
      id: memoryId,
      userId: this.userId,
      text: text,
      embedding: [], // Would be generated from text
      metadata: metadata,
      tags: tags,
      createdAt: new Date(),
      updatedAt: new Date()
    };

    this.memories.set(memoryId, memory);
    console.log(`📝 Memory added for user ${this.userId}: ${text.substring(0, 100)}...`);
    
    return memory;
  }

  searchMemories(query, limit = 10, threshold = 0.7) {
    const results = Array.from(this.memories.values())
      .map(memory => ({
        ...memory,
        similarity: 0.85 // Mock similarity score
      }))
      .filter(r => r.similarity >= threshold)
      .slice(0, limit);

    console.log(`🔍 Memory search for user ${this.userId}: "${query}" -> ${results.length} results`);
    return results;
  }

  getStats() {
    const memories = Array.from(this.memories.values());
    return {
      totalMemories: memories.length,
      oldestMemory: memories.length > 0 ? memories[0].createdAt : null,
      newestMemory: memories.length > 0 ? memories[memories.length - 1].createdAt : null,
      userIsolation: '100% isolated',
      evolution: memories.length > 5 ? 'Active learning' : 'Initial stage'
    };
  }

  // Clear all memories (100% user isolation)
  clear() {
    this.memories.clear();
    console.log(`��️ All memories cleared for user ${this.userId}`);
    return true;
  }
}

// User-isolated memory managers
const memoryManagers = new Map();

const getUserMemoryManager = (userId) => {
  if (!memoryManagers.has(userId)) {
    memoryManagers.set(userId, new MemoryManager(userId));
  }
  return memoryManagers.get(userId);
};

