app.post('/api/process/multimodal', upload.fields([
  { name: 'audio', maxCount: 1 },
  { name: 'image', maxCount: 1 }
]), async (req, res) => {
  try {
    const { userId } = req;
    const { text } = req.body;
    
    if (!text && !req.files?.audio && !req.files?.image) {
      return res.status(400).json({ error: 'No content provided' });
    }

    const results = {
      text: null,
      audio: null,
      image: null
    };

    // Process text
    if (text) {
      const embedding = await provider.embed(text);
      results.text = {
        content: text,
        embedding: embedding.embedding,
        dimensions: embedding.dimensions
      };
    }

    // Process audio
    if (req.files?.audio) {
      const audioFile = req.files.audio[0];
      const transcription = await provider.transcribe(audioFile.buffer, audioFile.mimetype);
      results.audio = {
        transcription: transcription.text,
        confidence: transcription.confidence,
        provider: transcription.provider
      };
    }

    // Process image
    if (req.files?.image) {
      const imageFile = req.files.image[0];
      const analysis = await provider.analyzeImage(imageFile.buffer, imageFile.mimetype);
      results.image = {
        analysis: {
          description: analysis.description,
          objects: analysis.objects,
          scene: analysis.scene,
          text: analysis.text
        },
        provider: analysis.provider
      };
    }

    // Combine insights
    const memoryManager = getUserMemoryManager(userId);
    const combinedText = [
      text || '',
      results.audio?.transcription || '',
      results.image?.analysis?.description || ''
    ].filter(t => t).join(' ');
    
    if (combinedText.trim()) {
      memoryManager.addMemory(
        `Multimodal insight: ${combinedText.substring(0, 200)}...`,
        { type: 'multimodal', sources: ['text', 'audio', 'image'].filter(s => results[s]) },
        ['multimodal', 'combined']
      );
    }

    res.json({
      success: true,
      userId,
      results,
      multimodal: true,
      userIsolation: '100% isolated',
      evolution: 'Combined insight created',
      processedAt: new Date().toISOString()
    });
  } catch (error) {
    console.error('Multimodal processing error:', error);
    res.status(500).json({ error: 'Multimodal processing failed', message: error.message });
  }
});

